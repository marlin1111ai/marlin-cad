// Same text the generator writes, byte for byte: ASCII STL, scene
// [x, y, z] -> file [x, -z, y], normals from the file-space vertices.
function toStlText(positions: readonly number[]): string {
  const lines = ["solid gridfinity_foot_test_piece"];
  for (let i = 0; i + 8 < positions.length; i += 9) {
    const toZUp = (x: number, y: number, z: number) => [x, -z, y] as const;
    const a = toZUp(positions[i], positions[i + 1], positions[i + 2]);
    const b = toZUp(positions[i + 3], positions[i + 4], positions[i + 5]);
    const c = toZUp(positions[i + 6], positions[i + 7], positions[i + 8]);
    const ux = b[0] - a[0];
    const uy = b[1] - a[1];
    const uz = b[2] - a[2];
    const vx = c[0] - a[0];
    const vy = c[1] - a[1];
    const vz = c[2] - a[2];
    const nx = uy * vz - uz * vy;
    const ny = uz * vx - ux * vz;
    const nz = ux * vy - uy * vx;
    const length = Math.hypot(nx, ny, nz) || 1;
    lines.push(
      `  facet normal ${nx / length} ${ny / length} ${nz / length}`,
      "    outer loop",
      `      vertex ${a[0]} ${a[1]} ${a[2]}`,
      `      vertex ${b[0]} ${b[1]} ${b[2]}`,
      `      vertex ${c[0]} ${c[1]} ${c[2]}`,
      "    endloop",
      "  endfacet",
    );
  }
  lines.push("endsolid gridfinity_foot_test_piece");
  return lines.join("\n") + "\n";
}

function parseStlToScenePositions(stl: string): number[] {
  const positions: number[] = [];
  const vertexPattern = /vertex\s+(-?[\d.eE+-]+)\s+(-?[\d.eE+-]+)\s+(-?[\d.eE+-]+)/g;
  let match: RegExpExecArray | null;
  while ((match = vertexPattern.exec(stl))) {
    const fx = Number(match[1]);
    const fy = Number(match[2]);
    const fz = Number(match[3]);
    // Inverse of [x, y, z] -> [x, -z, y]: scene x = file x, scene y = file z, scene z = -file y.
    // "0 - fy" rather than "-fy" so a file 0 comes back as 0, not -0.
    positions.push(fx, fz, 0 - fy);
  }
  return positions;
}

// Every directed edge must appear exactly once, with its reverse exactly
// once, keyed on the raw doubles -- the exact-stitch contract from
// CLAUDE-LESSONS.md. Returns the offending edges rather than asserting per
// edge, so a failure prints a short list instead of thousands of lines.
function directedEdgeDefects(positions: readonly number[]): string[] {
  const directed = new Map<string, number>();
  for (let i = 0; i + 8 < positions.length; i += 9) {
    const keys = [0, 3, 6].map((offset) => `${positions[i + offset]},${positions[i + offset + 1]},${positions[i + offset + 2]}`);
    for (let edge = 0; edge < 3; edge += 1) {
      const key = `${keys[edge]}|${keys[(edge + 1) % 3]}`;
      directed.set(key, (directed.get(key) ?? 0) + 1);
    }
  }
  const defects: string[] = [];
  for (const [key, count] of directed) {
    const [a, b] = key.split("|");
    if (count !== 1 || directed.get(`${b}|${a}`) !== 1) defects.push(key);
  }
  return defects;
}

// Heights at which a vertical ray through (x, z) crosses the mesh, lowest
// first, coincident crossings merged.
function verticalCrossings(positions: readonly number[], x: number, z: number): number[] {
  const crossings: number[] = [];
  for (let i = 0; i + 8 < positions.length; i += 9) {
    const p = positions;
    const denom = (p[i + 5] - p[i + 8]) * (p[i] - p[i + 6]) + (p[i + 6] - p[i + 3]) * (p[i + 2] - p[i + 8]);
    if (Math.abs(denom) < 1e-12) continue;
    const a = ((p[i + 5] - p[i + 8]) * (x - p[i + 6]) + (p[i + 6] - p[i + 3]) * (z - p[i + 8])) / denom;
    const b = ((p[i + 8] - p[i + 2]) * (x - p[i + 6]) + (p[i] - p[i + 6]) * (z - p[i + 8])) / denom;
    const c = 1 - a - b;
    if (a < 0 || b < 0 || c < 0) continue;
    crossings.push(a * p[i + 1] + b * p[i + 4] + c * p[i + 7]);
  }
  crossings.sort((m, n) => m - n);
  return crossings.filter((y, index) => index === 0 || y - crossings[index - 1] > 1e-9);
}

// X positions at which a ray along +X at height y and depth z crosses the
// mesh, lowest first, coincident crossings merged.
function crossingsAlongX(positions: readonly number[], y: number, z: number): number[] {
  const crossings: number[] = [];
  for (let i = 0; i + 8 < positions.length; i += 9) {
    const p = positions;
    // Barycentric coordinates of (y, z) in the triangle's (y, z) projection.
    const denom = (p[i + 5] - p[i + 8]) * (p[i + 1] - p[i + 7]) + (p[i + 7] - p[i + 4]) * (p[i + 2] - p[i + 8]);
    if (Math.abs(denom) < 1e-12) continue;
    const a = ((p[i + 5] - p[i + 8]) * (y - p[i + 7]) + (p[i + 7] - p[i + 4]) * (z - p[i + 8])) / denom;
    const b = ((p[i + 8] - p[i + 2]) * (y - p[i + 7]) + (p[i + 1] - p[i + 7]) * (z - p[i + 8])) / denom;
    const c = 1 - a - b;
    if (a < 0 || b < 0 || c < 0) continue;
    crossings.push(a * p[i] + b * p[i + 3] + c * p[i + 6]);
  }
  crossings.sort((m, n) => m - n);
  return crossings.filter((x, index) => index === 0 || x - crossings[index - 1] > 1e-9);
}

// Measures one foot of a mesh the way the reference STL was measured: from
// the vertices of the foot's own walls standing at `height` inside that
// foot's 42mm square. Only wall triangles are read (those that also reach
// the neighbouring profile level), so the plate's underside, which shares
// the foot top's height, is left out. Plan size is the vertices' extent; the
// corner radius is read from where the straight edge on the high-X side
// stops, and checked against the distance of every corner point from the
// arc's centre.
function measureFoot(positions: readonly number[], column: number, row: number, height: number) {
  const points = new Map<string, [number, number]>();
  const lowX = GRIDFINITY_PITCH * column - GRIDFINITY_FOOT_GAP / 2;
  const lowZ = GRIDFINITY_PITCH * row - GRIDFINITY_FOOT_GAP / 2;
  const index = MEASURED_PROFILE.findIndex((level) => level.height === height);
  const neighbour = MEASURED_PROFILE[index === 0 ? 1 : index - 1].height;
  for (let i = 0; i + 8 < positions.length; i += 9) {
    const heights = [positions[i + 1], positions[i + 4], positions[i + 7]];
    if (!heights.some((y) => Math.abs(y - neighbour) < 1e-9)) continue;
    for (let vertex = 0; vertex < 3; vertex += 1) {
      if (Math.abs(heights[vertex] - height) > 1e-9) continue;
      const x = positions[i + vertex * 3];
      const z = positions[i + vertex * 3 + 2];
      if (x < lowX || x > lowX + GRIDFINITY_PITCH || z < lowZ || z > lowZ + GRIDFINITY_PITCH) continue;
      points.set(`${x},${z}`, [x, z]);
    }
  }
  const all = [...points.values()];
  const minX = Math.min(...all.map((point) => point[0]));
  const maxX = Math.max(...all.map((point) => point[0]));
  const minZ = Math.min(...all.map((point) => point[1]));
  const maxZ = Math.max(...all.map((point) => point[1]));
  const onHighX = all.filter((point) => Math.abs(point[0] - maxX) < 1e-9).map((point) => point[1]);
  const radius = maxZ - Math.max(...onHighX);
  const arcCentre = [maxX - radius, maxZ - radius];
  const arc = all.filter((point) => point[0] >= arcCentre[0] - 1e-9 && point[1] >= arcCentre[1] - 1e-9);
  const distances = arc.map((point) => Math.hypot(point[0] - arcCentre[0], point[1] - arcCentre[1]));
  return {
    sizeX: maxX - minX,
    sizeZ: maxZ - minZ,
    centreX: (minX + maxX) / 2,
    centreZ: (minZ + maxZ) / 2,
    radius,
    arcPoints: arc.length,
    arcRadiusMin: Math.min(...distances),
    arcRadiusMax: Math.max(...distances),
  };
}

// Asserts a list of crossings against the expected one. Crossings are
// interpolated across a triangle, so they are compared to 1e-9, not exactly.
function expectCrossings(actual: number[], expected: number[]) {
  expect(actual.length, `crossings [${actual.join(", ")}]`).toBe(expected.length);
  expected.forEach((value, index) => expect(actual[index]).toBeCloseTo(value, 9));
}

// Area of a rounded square whose corner arcs are polygons of
// GRIDFINITY_FOOT_CORNER_SEGMENTS segments, as the mesh builds them.
function outlineArea(sizeX: number, sizeZ: number, radius: number): number {
  const segments = 4 * GRIDFINITY_FOOT_CORNER_SEGMENTS;
  const cornerPolygons = (segments / 2) * radius * radius * Math.sin((2 * Math.PI) / segments);
  return sizeX * sizeZ - 4 * radius * radius + cornerPolygons;
}

// Volume of one foot: between two levels the outline's size and radius run
// linearly, so its area is a quadratic in height and Simpson's rule is
// exact.
function footVolume(): number {
  let volume = 0;
  for (let level = 0; level + 1 < MEASURED_PROFILE.length; level += 1) {
    const low = MEASURED_PROFILE[level];
    const high = MEASURED_PROFILE[level + 1];
    const middleSize = (low.size + high.size) / 2;
    const middleRadius = (low.radius + high.radius) / 2;
    volume +=
      ((high.height - low.height) / 6) *
      (outlineArea(low.size, low.size, low.radius) + 4 * outlineArea(middleSize, middleSize, middleRadius) + outlineArea(high.size, high.size, high.radius));
  }
  return volume;
}

