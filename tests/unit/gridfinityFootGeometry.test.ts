describe("gridfinityFootPositions: N x M grids", () => {
  for (const [squaresX, squaresZ] of GRIDS) {
    const name = `${squaresX} x ${squaresZ}`;
    const positions = gridfinityFootPositions({ squaresX, squaresZ });
    const dimensions = gridfinityFootDimensions({ squaresX, squaresZ });

    it(`${name}: watertight, manifold, exact directed-edge manifold`, () => {
      expect(positions.every(Number.isFinite)).toBe(true);
      const analysis = analyzeTriangleSoup(positions);
      expect(analysis.boundaryEdges).toBe(0);
      expect(analysis.nonManifoldEdges).toBe(0);
      expect(analysis.degenerateTriangles).toBe(0);
      expect(directedEdgeDefects(positions)).toEqual([]);
    });

    it(`${name}: volume is the plate plus ${squaresX * squaresZ} feet`, () => {
      const plate = outlineArea(dimensions.width, dimensions.depth, GRIDFINITY_FOOT_TOP_RADIUS) * dimensions.plateThickness;
      const analysis = analyzeTriangleSoup(positions);
      expect(Math.abs(analysis.volume)).toBeCloseTo(plate + squaresX * squaresZ * footVolume(), 6);
      // Signed, from the raw triangles: positive means every face is wound
      // outward, which the directed-edge test alone cannot tell from every
      // face wound inward.
      let signed = 0;
      for (let i = 0; i + 8 < positions.length; i += 9) {
        const [ax, ay, az, bx, by, bz, cx, cy, cz] = positions.slice(i, i + 9);
        signed += (ax * (by * cz - bz * cy) - ay * (bx * cz - bz * cx) + az * (bx * cy - by * cx)) / 6;
      }
      expect(signed).toBeGreaterThan(0);
    });

    it(`${name}: every foot measures the reference profile and sits on the 42mm pitch`, () => {
      for (let column = 0; column < squaresX; column += 1) {
        for (let row = 0; row < squaresZ; row += 1) {
          for (const level of MEASURED_PROFILE) {
            const measured = measureFoot(positions, column, row, level.height);
            expect(measured.sizeX).toBeCloseTo(level.size, 9);
            expect(measured.sizeZ).toBeCloseTo(level.size, 9);
            expect(measured.radius).toBeCloseTo(level.radius, 9);
            expect(measured.arcPoints).toBe(GRIDFINITY_FOOT_CORNER_SEGMENTS + 1);
            expect(measured.arcRadiusMin).toBeCloseTo(level.radius, 9);
            expect(measured.arcRadiusMax).toBeCloseTo(level.radius, 9);
            expect(measured.centreX).toBeCloseTo(20.75 + 42 * column, 9);
            expect(measured.centreZ).toBeCloseTo(20.75 + 42 * row, 9);
          }
        }
      }
    });
  }

  // 3 x 3 is the smallest grid with a foot that touches no edge of the
  // plate: all four of its corners carry a fan and all four of its sides a
  // strip.
  it("3 x 3: the plate's underside is open to the bed between every pair of feet, and closed by a foot under every square", () => {
    const positions = gridfinityFootPositions({ squaresX: 3, squaresZ: 3 });
    for (let column = 0; column < 3; column += 1) {
      for (let row = 0; row < 3; row += 1) {
        const x = 20.75 + 42 * column;
        const z = 20.75 + 42 * row;
        expectCrossings(verticalCrossings(positions, x + 0.013, z + 0.007), [0, 7.75]);
        // In the 0.5mm gap beside this foot, and where four gaps cross.
        if (column < 2) expectCrossings(verticalCrossings(positions, x + 21, z + 0.007), [4.75, 7.75]);
        if (row < 2) expectCrossings(verticalCrossings(positions, x + 0.013, z + 21), [4.75, 7.75]);
        if (column < 2 && row < 2) expectCrossings(verticalCrossings(positions, x + 21.013, z + 21.007), [4.75, 7.75]);
      }
    }
  });
});

